Let Boss be a relation.
Let alice be an entity.

Therefore A in SET.
Therefore Boss in RELATION.
Therefore SET in SET.

-- RELATION is a subset of SET, so Boss is a set too.
By rule (relation is set) applied to (Boss), it follows that Boss in SET.
Therefore Boss in SET.

