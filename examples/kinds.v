-- `be a set` / `be a relation` là nội dung: nó ghi một fact, không đặt ra loại.

Let A, B be sets.
Let Boss be a relation.
Let alice be an entity.

Therefore A in SET.
Therefore Boss in RELATION.
Therefore SET in SET.

-- RELATION là tập con của SET, nên Boss cũng là một set.
By rule (relation is set) applied to (Boss), it follows that Boss in SET.
Therefore Boss in SET.

-- alice không được nói gì thêm. Ô (alice, SET) chưa ai nói gì — không phải
-- "sai", chỉ là chưa biết. `Therefore alice in SET.` sẽ báo SAI, và cả
-- `Therefore alice notin SET.` cũng vậy.
